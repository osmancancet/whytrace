#!/usr/bin/env python3
"""Compute per-variant calibration (mean confidence on correct vs wrong) and
Brier score (one-vs-rest on the chosen verdict) across the three test sets
(dev, seen held-out ho, blind hb). No logic change — pure read-only
re-aggregation over committed evidence tables.

Usage: python3 scripts/eval_calibration.py > evidence/calibration.md

The script parses the per-row (verdict, ok, conf) columns from:
  evidence/eval.md                    (dev 7×3 DAY3D snapshot, A0+B0+M0)
  evidence/heldout-eval.md            (ho run 1 originals + B0/M0 24 rows)
  evidence/heldout-eval-rerun.md      (ho A0 reruns 16 rows, model-backed)
  evidence/heldout-b-eval.md          (hb 8×3 clean, A0+B0+M0)
  evidence/day7-regression.md         (DAY7 v2 one-run dev+ho sanity)

Brier score (one-vs-rest on the chosen verdict): for each row with predicted
verdict V at confidence p, the target probability is 1 if the actual verdict is
V (row is ok) and 0 otherwise, so the per-row loss is (p-1)^2 when ok and p^2
when wrong. Lower is better; range [0,1]; a confident wrong answer costs more.
"""
import os, re, sys
from statistics import mean

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def parse_table(md: str, header: str):
    m = re.search(r'## ' + re.escape(header) + r'.*?\n(.*?)(?=\n## |\Z)', md, re.S)
    if not m:
        return []
    rows = []
    for line in m.group(1).split('\n'):
        line = line.strip()
        if not line.startswith('| ') or '---' in line or line.startswith('| case |'):
            continue
        cells = [c.strip() for c in line.strip('|').split('|')]
        if len(cells) < 6 or cells[0] in ('case', ''):
            continue
        try:
            conf = float(cells[5])
        except ValueError:
            continue
        rows.append({
            'case': cells[0], 'expected': cells[1], 'run': cells[2],
            'verdict': cells[3], 'ok': cells[4] == '✅', 'conf': conf,
        })
    return rows

def brier(rows):
    if not rows:
        return None
    return mean([((r['conf'] - 1) ** 2) if r['ok'] else (r['conf'] ** 2) for r in rows])

def stats(rows):
    if not rows:
        return None
    c = [r['conf'] for r in rows if r['ok']]
    w = [r['conf'] for r in rows if not r['ok']]
    return {
        'n': len(rows), 'ok': len(c),
        'mcc': round(mean(c), 3) if c else None,
        'mcw': round(mean(w), 3) if w else None,
        'brier': round(brier(rows), 4),
    }

def rd(p):
    full = os.path.join(ROOT, p)
    if not os.path.exists(full):
        return None
    return open(full, encoding='utf-8').read()

def fmt(cell):
    return '—' if cell is None else str(cell)

def row_md(label, s):
    if not s:
        return f'| {label} | — | — | — | — |'
    return f"| {label} | {s['ok']}/{s['n']} | {fmt(s['mcc'])} | {fmt(s['mcw'])} | {s['brier']:.4f} |"

A0_HDR = 'A0 — full system'
B0_HDR = 'B0 — rules-only baseline (Entra-style thresholds)'
M0_HDR = 'M0 — model-only (Nemotron alone, no tools, no critic, no risk gate)'

def main():
    ev = rd('evidence/eval.md') or ''
    heldout = rd('evidence/heldout-eval.md') or ''
    rerun = rd('evidence/heldout-eval-rerun.md') or ''
    hbev = rd('evidence/heldout-b-eval.md') or ''
    day7 = rd('evidence/day7-regression.md') or ''

    dev = {
        'A0': stats(parse_table(ev, A0_HDR)),
        'B0': stats(parse_table(ev, B0_HDR)),
        'M0': stats(parse_table(ev, M0_HDR)),
    }

    # ho A0 = originals run 1 (from heldout-eval.md) + reruns runs 2+3 (rerun file)
    ho_A0_orig = [r for r in parse_table(heldout, A0_HDR) if r['run'] == '1']
    ho_A0_rerun = parse_table(rerun, A0_HDR)
    ho = {
        'A0': stats(ho_A0_orig + ho_A0_rerun),
        'B0': stats(parse_table(heldout, B0_HDR)),
        'M0': stats(parse_table(heldout, M0_HDR)),
    }

    hb = {
        'A0': stats(parse_table(hbev, A0_HDR)),
        'B0': stats(parse_table(hbev, B0_HDR)),
        'M0': stats(parse_table(hbev, M0_HDR)),
    }

    # DAY7 v2 one-run sanity (dev+ho on v2)
    v2 = parse_table(day7, A0_HDR)
    v2_dev = [r for r in v2 if r['case'].startswith('case-')]
    v2_ho = [r for r in v2 if r['case'].startswith('ho-')]
    v2 = {'dev': stats(v2_dev), 'ho': stats(v2_ho)}

    out = []
    out.append('# Calibration — mean confidence (correct vs wrong) and Brier score')
    out.append('')
    out.append('_Generated by `python3 scripts/eval_calibration.py` from committed evidence tables; no live runs. No logic changes between runs — presentation only._')
    out.append('')
    out.append('**Brier score (one-vs-rest on the chosen verdict).** For every row with predicted verdict V at confidence p, the target probability is 1 if the actual verdict was V (row ok) and 0 otherwise. The per-row loss is `(p - 1)^2` when ok and `p^2` when wrong, averaged across rows. Lower is better; range [0, 1]; a confident wrong answer costs the most.')
    out.append('')
    out.append('Columns:')
    out.append('- **ok/n** — correct verdicts over counted rows (same rows as the evidence tables).')
    out.append('- **mean conf · correct** — mean confidence on rows the system got right.')
    out.append('- **mean conf · wrong** — mean confidence on rows the system got wrong.')
    out.append('- **Brier** — one-vs-rest Brier score across all rows.')
    out.append('')

    for key, title, src in [
        ('dev', 'Dev set — 7 cases × 3 runs = 21 rows (DAY3D snapshot in `evidence/eval.md`)', dev),
        ('ho',  'Seen held-out ho — 8 cases × 3 runs = 24 rows (A0 originals run 1 + reruns runs 2-3; B0/M0 from `evidence/heldout-eval.md`)', ho),
        ('hb',  'Blind held-out hb — 8 cases × 3 runs = 24 rows (`evidence/heldout-b-eval.md`, no reruns needed)', hb),
    ]:
        out.append(f'## {title}')
        out.append('')
        out.append('| variant | ok/n | mean conf · correct | mean conf · wrong | Brier (lower = better) |')
        out.append('|---|---|---|---|---|')
        out.append(row_md('A0 (WhyTrace)', src['A0']))
        out.append(row_md('B0 (rules-only)', src['B0']))
        out.append(row_md('M0 (Nemotron alone)', src['M0']))
        out.append('')

    out.append('## DAY7 v2 one-run sanity — A0 only (`evidence/day7-regression.md`)')
    out.append('')
    out.append('| set | ok/n | mean conf · correct | mean conf · wrong | Brier |')
    out.append('|---|---|---|---|---|')
    out.append(row_md('dev (7)', v2['dev']))
    out.append(row_md('seen ho (8)', v2['ho']))
    out.append('')

    out.append('## Honest reading')
    out.append('')
    out.append('- **A0 is better-calibrated than B0 and M0 on dev** (Brier 0.0905 vs 0.295 vs 0.2572). On the blind hb set the three sit close together (0.21–0.24): B0 and M0 keep confidence high on both correct and wrong rows, A0 trims confidence when a case escalates to a human.')
    out.append('- **M0 is the worst-calibrated across every set.** Its mean confidence on wrong rows is 0.80+ in every column — Nemotron alone is confident even when it is wrong. That is the symptom the agent architecture is built to cushion.')
    out.append('- **A0 keeps a visible gap between correct-confidence and wrong-confidence on dev + ho.** On hb the gap narrows (0.729 vs 0.654) because the three hb misses are all mid-confidence over-escalations the agent surfaces to a human rather than committing to a verdict — the policy adds a -0.1 degraded humility penalty on contested chains.')
    out.append('- **Zero false contain / false benign on A0 across all three sets is still the headline.** Calibration adds colour; the error-shape invariant (never silently lock a real user, never silently clear a real attack) is what makes the Brier number meaningful.')
    out.append('')

    sys.stdout.write('\n'.join(out).rstrip() + '\n')

if __name__ == '__main__':
    main()
