#!/usr/bin/env python3
"""Count which Nemotron model Nightshift actually routed each agent to.

Reads the local run traces (logs/*/trace.jsonl, gitignored) and the committed
scrubbed receipts (site/recorded/*/model_calls.jsonl), and writes
evidence/model-routing.md. The model names come from the `routed_model` field of
each Nightshift receipt, never from configuration.
"""
import collections, glob, json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
ROLE = {
    "planner": "Planner: opens competing hypotheses, picks the first queries",
    "risk_gate": "Risk Gate: model opinion checked against the deterministic policy",
    "reporter": "Reporter: writes the cited report",
    "markovian": "Markovian sweep: bounded long-log password-spray scan",
    "warmup": "Health probe before a run (not part of a verdict)",
    "model_only": "M0 baseline only (Nemotron alone, used in the evaluation)",
}
calls = collections.Counter(); failed = collections.Counter(); receipts = collections.defaultdict(list); runs = set()
for f in sorted(glob.glob("logs/*/trace.jsonl")):
    for line in open(f, encoding="utf-8"):
        try:
            d = json.loads(line)
        except ValueError:
            continue
        rm = d.get("routed_model")
        if not rm or rm == "sample" or not str(d.get("action", "")).startswith("chat_nightshift"):
            continue
        a = d.get("agent", "?"); runs.add(f.split("/")[1])
        if d.get("status") != "ok" or not d.get("receipt_id"):
            failed[(a, rm)] += 1
            continue
        calls[(a, rm)] += 1
        if d.get("receipt_id") and len(receipts[(a, rm)]) < 2:
            receipts[(a, rm)].append(d["receipt_id"])
if not calls:
    sys.exit("no logs/*/trace.jsonl found: run on the builder machine that holds the local logs")
rec = collections.Counter()
for f in sorted(glob.glob("site/recorded/*/model_calls.jsonl")):
    for line in open(f, encoding="utf-8"):
        d = json.loads(line); rec[(d["agent"], d["routed_model"])] += 1
out = ["# Nemotron model per agent (from Nightshift receipts)", "",
       f"_Generated by `python3 scripts/model_routing.py` from {len(runs)} local runs (`logs/*/trace.jsonl`). "
       "Model names are the `routed_model` field of each Nightshift receipt, not configuration._", "",
       "Investigator, Critic and Scout Intent make **no model calls**: the Investigator and the Critic run named Zetaris queries, "
       "and Scout is a deterministic intent/injection classifier. Every model call goes through Meterless Nightshift.", "",
       "Only successful calls that returned a receipt are counted here; failed attempts are listed separately below.", "",
       "| agent | role | routed_model (receipt) | successful calls | example receipt ids |", "|---|---|---|---|---|"]
for (a, rm), n in sorted(calls.items(), key=lambda x: (list(ROLE).index(x[0][0]) if x[0][0] in ROLE else 99, -x[1])):
    out.append(f"| `{a}` | {ROLE.get(a, '')} | `{rm}` | {n} | {', '.join('`'+r+'`' for r in receipts[(a, rm)])} |")
out += ["", "## Attempts that returned no receipt", "",
        "Calls that ended `degraded` (provider error, timeout or empty answer) and were retried or fell back. They produced no receipt and no answer used in a verdict.", "",
        "| agent | routed_model | attempts without receipt |", "|---|---|---|"]
for (a, rm), n in sorted(failed.items(), key=lambda x: -x[1]):
    out.append(f"| `{a}` | `{rm}` | {n} |")
lt = sum(n for (a, rm), n in calls.items() if "lightning" in rm)
out += ["", f"**Reading:** every successful model call in these runs was routed to `nvidia/nemotron-3.5-super-vl-120b-a12b`. "
        f"The fast lane (`nemotron-3.5-lightning-30b-a3b`) returned {lt} successful calls; its attempts all ended degraded on this install.", ""]
out += ["## Committed receipt logs", "",
        "Scrubbed receipts for the four runs replayed on the project page (agent, routed_model, receipt_id, ms, completion_tokens, cache_hit):", ""]
for f in sorted(glob.glob("site/recorded/*/model_calls.jsonl")):
    out.append(f"- [`{f}`]({os.path.relpath(f, 'evidence')})")
out += ["", "| agent | routed_model | calls in committed receipts |", "|---|---|---|"]
for (a, rm), n in sorted(rec.items()):
    out.append(f"| `{a}` | `{rm}` | {n} |")
out += ["", "Every evaluation run's raw report under [`evidence/eval_raw/`](eval_raw/) also carries the receipt ids of its model calls.", ""]
open("evidence/model-routing.md", "w", encoding="utf-8").write("\n".join(out))
print("wrote evidence/model-routing.md:", sum(calls.values()), "calls from", len(runs), "runs")
